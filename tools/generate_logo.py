#!/usr/bin/env python3
"""Resize the supplied logo and generate a ready-to-draw LVGL RGB565 resource.

Requires Pillow only when regenerating assets. Firmware builds need no image tools.
"""
from pathlib import Path
import argparse
import hashlib
import json
import shutil
import struct
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
FOLDER = ROOT / 'assets/startup'
ORIGINAL = FOLDER / 'mercedes-logo-original.png'

def generate(source=None):
    FOLDER.mkdir(parents=True, exist_ok=True)
    if source and source.resolve() != ORIGINAL.resolve():
        shutil.copyfile(source, ORIGINAL)
    with Image.open(ORIGINAL) as source_image:
        rgba = source_image.convert('RGBA')
        black = Image.new('RGBA', rgba.size, (0, 0, 0, 255))
        black.alpha_composite(rgba)
        fitted = ImageOps.contain(black.convert('RGB'), (466, 466), Image.Resampling.LANCZOS)
    image = Image.new('RGB', (466, 466), (0, 0, 0))
    image.paste(fitted, ((466-fitted.width)//2, (466-fitted.height)//2))
    png = FOLDER / 'mercedes-logo-466.png'
    image.save(png)
    raw = bytearray()
    for r, g, b in struct.iter_unpack('BBB', image.tobytes()):
        raw.extend(struct.pack('<H', ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)))
    assert len(raw) == 466 * 466 * 2
    assert all(image.getpixel(p) == (0, 0, 0) for p in [(0, 0), (465, 0), (0, 465), (465, 465)])
    rows = ['    ' + ','.join(f'0x{x:02x}' for x in raw[i:i+24]) + ',' for i in range(0, len(raw), 24)]
    code = '''/* Generated by tools/generate_logo.py from the user-supplied logo. */
#include <lvgl.h>

static const LV_ATTRIBUTE_MEM_ALIGN uint8_t logo_pixels[] = {
''' + '\n'.join(rows) + '''
};

const lv_image_dsc_t hud_mercedes_logo = {
    .header = {
        .magic = LV_IMAGE_HEADER_MAGIC,
        .cf = LV_COLOR_FORMAT_RGB565,
        .flags = 0,
        .w = 466,
        .h = 466,
        .stride = 932,
    },
    .data_size = sizeof(logo_pixels),
    .data = logo_pixels,
    .reserved = NULL,
    .reserved_2 = NULL,
};
'''
    (ROOT/'src/hud/mercedes_logo.c').write_text(code)
    metadata = {
        'source': ORIGINAL.name, 'source_sha256': hashlib.sha256(ORIGINAL.read_bytes()).hexdigest(),
        'image': png.name, 'width': 466, 'height': 466, 'background': '#000000',
        'format': 'RGB565 little-endian, opaque', 'raw_bytes': len(raw),
        'raw_sha256': hashlib.sha256(raw).hexdigest(),
    }
    (FOLDER/'manifest.json').write_text(json.dumps(metadata, ensure_ascii=False, indent=2)+'\n')
    print(json.dumps(metadata, ensure_ascii=False))

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, help='Original PNG; defaults to the bundled source image.')
    generate(parser.parse_args().source)
