#!/usr/bin/env python3
"""Generate deterministic firmware tables from the shared OBD definition."""
from pathlib import Path
import json
ROOT=Path(__file__).resolve().parents[1]
d=json.loads((ROOT/'config/obd_profiles.json').read_text())
rows=[]
for m in d['metrics']:
 p=m['pids']; rows.append('    {{'+','.join(map(str,p+[0]*(4-len(p))))+'},'+str(len(p))+','+str(m['bytes'])+',{' + ','.join(map(str,m['periods']))+'}}')
p=d['pressure']; t=d['timing']
s='''// Generated by tools/generate_profiles.py; edit config/obd_profiles.json.
#pragma once
namespace hud {
struct MetricDefinition { uint8_t pids[4]; uint8_t count,bytes; uint32_t periods[2]; };
inline constexpr MetricDefinition MetricDefinitions[]={
'''+',\n'.join(rows)+'''\n};
inline constexpr const char* ProfileNames[]={'''+','.join(json.dumps(x['name'],ensure_ascii=False) for x in d['profiles'])+'''};
inline constexpr const char* ProfileIds[]={'''+','.join(json.dumps(x['id']) for x in d['profiles'])+'''};
inline constexpr unsigned ProfileCount='''+str(len(d['profiles']))+''';
inline constexpr uint8_t ProfileDefaultProtocols[]={'''+','.join(str(x.get('default_protocol',0)) for x in d['profiles'])+'''};
inline constexpr bool ProfilePressureEnabled[]={'''+','.join(str(x['pressure']).lower() for x in d['profiles'])+'''};
inline constexpr uint32_t RetryBackoff[]={'''+','.join(map(str,t['backoff_ms']))+'''};
inline constexpr int SplashBrightnessPercent='''+str(t['splash_brightness'])+''';
inline constexpr uint32_t SplashDurationMs='''+str(t['splash_ms'])+''',SplashFadeMs='''+str(t['fade_ms'])+''',ConnectionTimeoutMs='''+str(t['notice_ms'])+''',HeartbeatIntervalMs='''+str(t['heartbeat_ms'])+''',IdentityRetryMs='''+str(t['identity_retry_ms'])+''';
inline constexpr uint32_t DiscoveryTimeoutMs='''+str(t['round_ms'])+''',CachedTimeoutMs='''+str(t['cached_ms'])+''',SilenceTimeoutMs='''+str(t['silence_ms'])+''';
inline constexpr uint8_t PressureProtocol='''+str(p['protocol'])+''',PressureStandardProtocol='''+str(p['required_standard_protocol'])+''';
inline constexpr const char* PressureReceiveCommand="ATCRA'''+p['rx']+'''";
inline constexpr uint32_t PressureRx=0x'''+p['rx']+''';
inline constexpr const char* PressureTx="'''+p['tx']+'''";
inline constexpr const char* PressureCommand="'''+p['command']+'''";
inline constexpr double PressureDivisor='''+str(p['divisor'])+''';
inline constexpr unsigned PressureOffset='''+str(p['offset'])+''';
inline constexpr uint8_t PressurePrefix[]={'''+','.join('0x'+p['prefix'][i:i+2] for i in range(0,len(p['prefix']),2))+'''};
}
'''
out=ROOT/'src/hud/profiles_generated.hpp'
if not out.exists() or out.read_text()!=s:out.write_text(s)
